#!/usr/bin/env node
// Generate src/generated/tokens.css and tokens.ts from vendor/tokens.json (BUILD-SPEC v2 §7.1).
// vendor/ is filled by `pnpm ui:sync` (apps/fincrime-host/docs/ui/tokens.json + assets/fonts).
//   node packages/ui-tokens/scripts/build-tokens.mjs
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(pkg, "vendor");
const out = join(pkg, "src/generated");
const source = join(vendor, "tokens.json");

if (!existsSync(source)) {
  console.error("ui-tokens: vendor/tokens.json is missing. Run `pnpm ui:sync` first.");
  process.exit(1);
}
const tokens = JSON.parse(readFileSync(source, "utf8"));

/** `{porcelain-100}` → `var(--porcelain-100)`; plain values pass through. */
const value = (raw) => String(raw).replace(/\{([a-z0-9-]+)\}/gi, "var(--$1)");
const declarations = (group) =>
  Object.entries(group)
    .filter(([name]) => !name.startsWith("$"))
    .map(([name, token]) => `  --${name}: ${value(token.$value)};`);

const ORDER = ["color", "semantic", "typography", "space", "radius", "elevation", "layout", "density", "motion", "z"];
const FONTS = [
  ["Instrument Sans", 400, "normal", "instrument-sans-latin-400-normal"],
  ["Instrument Sans", 500, "normal", "instrument-sans-latin-500-normal"],
  ["Instrument Sans", 600, "normal", "instrument-sans-latin-600-normal"],
  ["Instrument Sans", 700, "normal", "instrument-sans-latin-700-normal"],
  ["Instrument Serif", 400, "normal", "instrument-serif-latin-400-normal"],
  ["Instrument Serif", 400, "italic", "instrument-serif-latin-400-italic"],
  ["JetBrains Mono", 400, "normal", "jetbrains-mono-latin-400-normal"],
  ["JetBrains Mono", 500, "normal", "jetbrains-mono-latin-500-normal"],
];

const modes = tokens.modes ?? {};
const modeBlock = (selector, entries, indent = "  ") =>
  `${selector} {\n${Object.entries(entries).map(([name, raw]) => `${indent}--${name}: ${value(raw)};`).join("\n")}\n}`;

// tokens.json's compact mode shrinks body text to 13px; the reference CSS pairs that with an
// 18px line height (lh-sm), which the JSON does not spell out. Keep the pair together.
const compact = { ...modes.compact };
if (compact["text-md"] && !compact["lh-md"]) compact["lh-md"] = "{lh-sm}";

const css = [
  "/* Generated by packages/ui-tokens/scripts/build-tokens.mjs from apps/fincrime-host/docs/ui/tokens.json. Do not edit. */",
  ...FONTS.map(([family, weight, style, file]) =>
    `@font-face { font-family: "${family}"; font-weight: ${weight}; font-style: ${style}; font-display: swap; src: url("./fonts/${file}.woff2") format("woff2"); }`),
  "",
  ":root {",
  ...ORDER.flatMap((group) => (tokens[group] ? [`  /* ${group} */`, ...declarations(tokens[group])] : [])),
  "}",
  ':root { color-scheme: light; }',
  "",
  "/* Explicit preferences take precedence over the OS. System updates without JavaScript. */",
  modeBlock(':root[data-theme="dark"]', modes.dark ?? {}),
  ':root[data-theme="dark"] { color-scheme: dark; }',
  `@media (prefers-color-scheme: dark) {\n${modeBlock(':root:not([data-theme="light"]):not([data-theme="dark"])', modes.dark ?? {})}\n:root:not([data-theme="light"]):not([data-theme="dark"]) { color-scheme: dark; }\n}`,
  "",
  "/* Dense mode: same hierarchy, tighter rhythm (STYLE-GUIDE §4). */",
  modeBlock('[data-density="compact"]', compact),
  "",
  "/* Reduced motion: durations go to 0, state changes still apply (STYLE-GUIDE §6). */",
  `@media (prefers-reduced-motion: reduce) {\n${modeBlock("  :root", modes["reduced-motion"] ?? {}, "    ")}\n}`,
  modeBlock('[data-motion="reduced"]', modes["reduced-motion"] ?? {}),
  "",
  "/* High contrast: stronger hairlines and secondary ink (STYLE-GUIDE §9). */",
  `@media (prefers-contrast: more) {\n${modeBlock("  :root", modes["high-contrast"] ?? {}, "    ")}\n}`,
  modeBlock('[data-contrast="more"]', modes["high-contrast"] ?? {}),
  `@media (prefers-contrast: more) {\n${modeBlock(':root[data-theme="dark"]', modes["dark-high-contrast"] ?? {})}\n@media (prefers-color-scheme: dark) {\n${modeBlock(':root:not([data-theme="light"]):not([data-theme="dark"])', modes["dark-high-contrast"] ?? {})}\n}\n}`,
  modeBlock(':root[data-theme="dark"][data-contrast="more"]', modes["dark-high-contrast"] ?? {}),
  `@media (prefers-color-scheme: dark) {\n${modeBlock(':root[data-contrast="more"]:not([data-theme="light"]):not([data-theme="dark"])', modes["dark-high-contrast"] ?? {})}\n}`,
  "",
].join("\n");

const stateMap = Object.fromEntries(Object.entries(tokens.stateMap ?? {}).filter(([name]) => !name.startsWith("$")));
const ts = [
  "// Generated by packages/ui-tokens/scripts/build-tokens.mjs from apps/fincrime-host/docs/ui/tokens.json. Do not edit.",
  "",
  `export const STATE_MAP = ${JSON.stringify(stateMap, null, 2)} as const;`,
  "",
  `export const TOKEN_GROUPS = ${JSON.stringify(Object.fromEntries(ORDER.filter((group) => tokens[group]).map((group) => [group, Object.keys(tokens[group]).filter((name) => !name.startsWith("$"))])), null, 2)} as const;`,
  "",
  `export const FONT_FILES = ${JSON.stringify(FONTS.map(([family, weight, style, file]) => ({ family, weight, style, file: `${file}.woff2` })), null, 2)} as const;`,
  "",
].join("\n");

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "fonts"), { recursive: true });
for (const name of readdirSync(join(vendor, "fonts"))) cpSync(join(vendor, "fonts", name), join(out, "fonts", name));
writeFileSync(join(out, "tokens.css"), css);
writeFileSync(join(out, "tokens.ts"), ts);
console.log(`ui-tokens: tokens.css and tokens.ts generated (${Object.keys(stateMap).length} state dimensions).`);
