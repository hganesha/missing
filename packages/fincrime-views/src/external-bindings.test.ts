import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { validatorFor } from "@ehf/ui-contracts/validate";
import type { Schemas } from "@ehf/ui-contracts";
import type { CatalogSnapshot } from "./catalogs.js";
import { catalogIndex } from "./catalogs.js";
import { withExternalBindingRevisions } from "./external-bindings.js";
const snapshot = JSON.parse(readFileSync(new URL("../../ui-contracts/vendor/docs/ui/contracts/fixtures/catalogs.json", import.meta.url), "utf8")) as CatalogSnapshot;
const source = JSON.parse(readFileSync(new URL("../../../config/external-capability-bindings.json", import.meta.url), "utf8"));
it("projects edits into canonical search, grouping and contract semantics without mutating sources or releasing quarantine", async () => {
  const binding = source.bindings.find((item: { bindingId: string }) => item.bindingId.includes(":finantier:"));
  const revision: Schemas["ExternalBindingRevision"] = { bindingId: binding.bindingId, definition: { ...binding.definition, capabilityPath: "screening.sanctions", actions: ["screen"], jurisdiction: { code: "us", evidenceRefs: ["evidence:publisher"] } }, revision: 1, sourceDigest: binding.sourceDigest, digest: "a".repeat(64), reason: "Correct source semantics", updatedAt: "2026-11-08T00:00:00Z", updatedBy: "admin" };
  const updated = await withExternalBindingRevisions(snapshot, [revision]);
  const entry = updated.entries.find(item => item.id === binding.bindingId)!;
  expect(entry.group).toBe("Screening");
  expect(entry.collection).toBe('Screening and public datasets');
  expect(entry.status).toBe("quarantined");
  expect(entry.contract.capability_id).toBe("screening.sanctions.intelligence.us");
  expect(entry.contract.jurisdiction).toMatchObject({ basis: "dataset_authority", resolution_status: "proposed" });
  expect(entry.contract.governance).toMatchObject({ enabled: false, quarantine: true, approval_ref: null });
  expect(entry.contract.implementation).toMatchObject({ validation: "none", response_mapping: "not_defined" });
  expect(entry.relationships[0]?.id).toBe("screening.sanctions");
  expect(updated.digest).not.toBe(snapshot.digest);
  expect(entry.digest).toBe(createHash("sha256").update(JSON.stringify(entry.contract)).digest("hex"));
  expect(validatorFor("CatalogSnapshot")(updated)).toBe(true);
  expect(catalogIndex(updated, ["capability.read"], { kind: "external-capabilities", entryType: "binding", group: "Screening", q: "finantier" }).items.some(item => item.id === binding.bindingId)).toBe(true);
  expect(snapshot.entries.find(item => item.id === binding.bindingId)!.contract.capability_id).not.toBe(entry.contract.capability_id);
});
