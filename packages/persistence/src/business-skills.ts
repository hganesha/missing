import {
  BUSINESS_SKILL_MATURITY_LEVELS,
  businessSkillCatalogEntrySchema,
  businessSkillCatalogSchema,
  businessSkillDependencies,
  businessSkillEffects,
  businessSkillIdSchema,
  businessSkillManifestDigest,
  businessSkillManifestSchema,
  businessSkillMaturitySchema,
  businessSkillStatusSchema,
  semverSchema,
  type BusinessSkillDependencies,
  type BusinessSkillEffects,
  type BusinessSkillManifest,
  type BusinessSkillMaturity,
  type BusinessSkillStatus,
} from "@ehf/contracts";

/**
 * The business skill registry: the financial-crime skill library's catalog
 * (`entity.resolve`, `screening.sanctions.execute`, …), one row per skill version.
 *
 * These are business contracts, not the agent playbooks of the authoring registry
 * (`skill.kyc.*`). `config/business-skills.json` (generated by
 * scripts/sync-business-skills.mjs from the vendored catalog, config/skill-library) is the
 * seed. Seeding is additive and never lowers an operator decision: a version an operator
 * activated or deprecated keeps that status for identical content. Released/verified content
 * is permanently frozen by migration 035; draft content changes invalidate earlier maturity.
 * The seed only refreshes manifests whose digest changed. Two independent axes:
 * `status` (draft | active | deprecated) is the lifecycle, `maturity` (catalogued →
 * production_qualified) is how far the skill is proven. The stored manifest is the catalog
 * entry verbatim; `effects` and `dependencies` are derived from it, never stored.
 */
export type BusinessSkillClient = {
  query<T = Record<string, unknown>>(text: string, values?: unknown[]): Promise<{ rows: T[]; rowCount?: number | null }>;
};

export type BusinessSkillRecord = {
  skillId: string;
  semver: string;
  status: BusinessSkillStatus;
  maturity: BusinessSkillMaturity;
  owner: string;
  manifestDigest: string;
  effects: BusinessSkillEffects;
  dependencies: BusinessSkillDependencies;
  source: { path: string; revision: string };
  manifest: BusinessSkillManifest;
  createdAt: string;
  updatedAt: string;
};

type BusinessSkillRow = {
  skill_id: string;
  semver: string;
  manifest: unknown;
  manifest_digest: string;
  status: BusinessSkillStatus;
  maturity: BusinessSkillMaturity;
  source: { path: string; revision: string };
  owner: string;
  created_at: Date;
  updated_at: Date;
};

const COLUMNS = "skill_id, semver, manifest, manifest_digest, status, maturity, source, owner, created_at, updated_at";
const SEMVER_ORDER = "string_to_array(split_part(split_part(semver, '-', 1), '+', 1), '.')::int[] desc, semver desc";

function mapRow(row: BusinessSkillRow): BusinessSkillRecord {
  const manifest = businessSkillManifestSchema.parse(row.manifest);
  return {
    skillId: row.skill_id,
    semver: row.semver,
    status: row.status,
    maturity: row.maturity,
    owner: row.owner,
    manifestDigest: row.manifest_digest,
    effects: businessSkillEffects(manifest),
    dependencies: businessSkillDependencies(manifest),
    source: row.source,
    manifest,
    createdAt: row.created_at.toISOString(),
    updatedAt: row.updated_at.toISOString(),
  };
}

/**
 * Status rule for the seed: never lowers an operator decision. A deprecated version stays
 * deprecated and an active one stays active; an upstream deprecation always applies (like an
 * upstream connector quarantine); otherwise the catalog status is taken.
 */
const SEED_STATUS_MERGE = `
  case
    when business_skill_registry.status = 'deprecated' then 'deprecated'
    when excluded.status = 'deprecated' then 'deprecated'
    when business_skill_registry.status = 'active' then 'active'
    else excluded.status
  end`;

const MATURITY_LEVELS = `array[${BUSINESS_SKILL_MATURITY_LEVELS.map((level) => `'${level}'`).join(", ")}]`;

/** Preserve higher maturity only for identical content; changed drafts lose prior evidence. */
const SEED_MATURITY_MERGE = `
  case
    when business_skill_registry.manifest_digest is distinct from excluded.manifest_digest then excluded.maturity
    when array_position(${MATURITY_LEVELS}, business_skill_registry.maturity)
      > array_position(${MATURITY_LEVELS}, excluded.maturity) then business_skill_registry.maturity
    else excluded.maturity
  end`;

/**
 * Seed the registry from `config/business-skills.json`. The library catalog replaces the
 * Phase-1 spec-derived placeholders an earlier seed wrote (manifest `source:
 * spec-derived-placeholder`, maturity `catalogued`): they implemented nothing, so they are
 * removed rather than left beside the library versions.
 */
export async function seedBusinessSkillCatalog(db: BusinessSkillClient, input: unknown): Promise<{ created: number; updated: number; retired: number }> {
  const catalog = businessSkillCatalogSchema.parse(input);
  const retired = await db.query(`
    delete from harness_control.business_skill_registry
    where manifest->>'source' = 'spec-derived-placeholder'
  `);
  const rows = catalog.skills.map((entry) => ({
    skill_id: entry.skillId, semver: entry.semver, manifest: entry.manifest, manifest_digest: entry.manifestDigest,
    status: entry.status, maturity: entry.maturity, source: entry.source, owner: entry.owner,
  }));
  const result = await db.query<{ inserted: boolean }>(`
    insert into harness_control.business_skill_registry
      (skill_id, semver, manifest, manifest_digest, status, maturity, source, owner)
    select item->>'skill_id', item->>'semver', item->'manifest', item->>'manifest_digest',
      item->>'status', item->>'maturity', item->'source', item->>'owner'
    from jsonb_array_elements($1::jsonb) item
    on conflict (skill_id, semver) do update set
      manifest = excluded.manifest,
      manifest_digest = excluded.manifest_digest,
      source = excluded.source,
      owner = excluded.owner,
      status = case when business_skill_registry.manifest_digest is distinct from excluded.manifest_digest
        then 'draft' else ${SEED_STATUS_MERGE} end,
      maturity = ${SEED_MATURITY_MERGE},
      updated_at = now()
    where business_skill_registry.manifest_digest is distinct from excluded.manifest_digest
    returning (xmax = 0) inserted
  `, [JSON.stringify(rows)]);
  const created = result.rows.filter((row) => row.inserted).length;
  return { created, updated: result.rows.length - created, retired: retired.rowCount ?? 0 };
}

export type BusinessSkillFilter = { status?: BusinessSkillStatus; maturity?: BusinessSkillMaturity; domain?: string };

export async function listBusinessSkills(db: BusinessSkillClient, filter: BusinessSkillFilter = {}): Promise<BusinessSkillRecord[]> {
  const status = filter.status === undefined ? null : businessSkillStatusSchema.parse(filter.status);
  const maturity = filter.maturity === undefined ? null : businessSkillMaturitySchema.parse(filter.maturity);
  if (filter.domain !== undefined && !/^[a-z][a-z_]*$/.test(filter.domain)) throw new Error("business_skill.domain_invalid");
  const result = await db.query<BusinessSkillRow>(`
    select ${COLUMNS}
    from harness_control.business_skill_registry
    where ($1::text is null or status = $1)
      and ($2::text is null or maturity = $2)
      and ($3::text is null or skill_id like $3 || '.%')
    order by skill_id, ${SEMVER_ORDER}
  `, [status, maturity, filter.domain ?? null]);
  return result.rows.map(mapRow);
}

/** One skill version, or the highest registered version when `semver` is omitted. */
export async function getBusinessSkill(db: BusinessSkillClient, skillId: string, semver?: string): Promise<BusinessSkillRecord | null> {
  businessSkillIdSchema.parse(skillId);
  if (semver !== undefined) semverSchema.parse(semver);
  const result = await db.query<BusinessSkillRow>(`
    select ${COLUMNS}
    from harness_control.business_skill_registry
    where skill_id = $1 and ($2::text is null or semver = $2)
    order by ${SEMVER_ORDER}
    limit 1
  `, [skillId, semver ?? null]);
  const row = result.rows[0];
  return row ? mapRow(row) : null;
}

/**
 * Register or update one skill version outside the seed (e.g. an operator import). An
 * explicit `status` or `maturity` is the operator's decision and is applied as given; without
 * one the seed's never-lower rules apply.
 */
export async function upsertBusinessSkill(db: BusinessSkillClient, input: {
  manifest: unknown;
  status?: BusinessSkillStatus;
  maturity?: BusinessSkillMaturity;
  source: { path: string; revision: string };
}): Promise<{ record: BusinessSkillRecord; created: boolean }> {
  const manifest = businessSkillManifestSchema.parse(input.manifest);
  const entry = businessSkillCatalogEntrySchema.parse({
    skillId: manifest.id, semver: manifest.semver,
    status: input.status ?? ("status" in manifest ? manifest.status : undefined) ?? "draft",
    maturity: input.maturity ?? manifest.maturity ?? "catalogued",
    owner: manifest.owner, manifestDigest: businessSkillManifestDigest(input.manifest),
    effects: businessSkillEffects(manifest), dependencies: businessSkillDependencies(manifest), source: input.source,
    manifest: input.manifest,
  });
  const result = await db.query<BusinessSkillRow & { inserted: boolean }>(`
    insert into harness_control.business_skill_registry
      (skill_id, semver, manifest, manifest_digest, status, maturity, source, owner)
    values ($1, $2, $3::jsonb, $4, $5, $6, $7::jsonb, $8)
    on conflict (skill_id, semver) do update set
      manifest = excluded.manifest,
      manifest_digest = excluded.manifest_digest,
      source = excluded.source,
      owner = excluded.owner,
      status = case when $9::boolean then excluded.status else ${SEED_STATUS_MERGE} end,
      maturity = case when $10::boolean then excluded.maturity else ${SEED_MATURITY_MERGE} end,
      updated_at = now()
    returning ${COLUMNS}, (xmax = 0) inserted
  `, [
    entry.skillId, entry.semver, JSON.stringify(entry.manifest), entry.manifestDigest, entry.status, entry.maturity,
    JSON.stringify(entry.source), entry.owner, input.status !== undefined, input.maturity !== undefined,
  ]);
  const row = result.rows[0];
  if (!row) throw new Error("business_skill.upsert_failed");
  return { record: mapRow(row), created: row.inserted };
}
